// Development utility: append deterministic Ultralytics metadata to a TFLite
// artifact without changing the FlatBuffer bytes that contain the model graph.
//
// Run from the repository root (the base graph is not vendored):
//   dart run tool/package_ultralytics_metadata.dart --input=<base>.tflite
//
// docs/model-assets.md is hand-maintained. A measurement report is written only
// when --report=<path> is passed explicitly.
//
// The generated artifact is a normal TFLite FlatBuffer followed by a complete
// ZIP archive containing `metadata.json`.  This is the format consumed by
// ultralytics_yolo's native metadata loader.
import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';

import 'package:eyecue_flutter/models/tflite_flatbuffer.dart';

// The base (metadata-free) graph is no longer vendored; pass it explicitly.
const _defaultInput = '';
const _defaultOutput = 'assets/yolov8n_int8_new_metadata.tflite';
const _defaultLabels = 'assets/labels.txt';
const _expectedLabelCount = 80;
const _metadataEntryName = 'metadata.json';

void main(List<String> args) {
  try {
    final options = _Options.parse(args);
    final labels = _readLabels(options.labelsPath);
    final inputBytes = File(options.inputPath).readAsBytesSync();
    if (_zipContainsMetadata(inputBytes)) {
      throw StateError(
        'Input artifact ${options.inputPath} already contains a trailing ZIP '
        'payload. Start from the original base TFLite graph instead.',
      );
    }
    final baseStructure = _requireStructure(inputBytes, options.inputPath);
    final metadata = _buildMetadata(labels);
    final metadataBytes = Uint8List.fromList(utf8.encode(jsonEncode(metadata)));
    final zipBytes = _buildStoredZip(_metadataEntryName, metadataBytes);
    final generatedBytes = Uint8List(inputBytes.length + zipBytes.length)
      ..setRange(0, inputBytes.length, inputBytes)
      ..setRange(
        inputBytes.length,
        inputBytes.length + zipBytes.length,
        zipBytes,
      );
    final generatedStructure = _requireStructure(
      generatedBytes,
      options.outputPath,
    );

    _assertSameStructure(baseStructure, generatedStructure);
    if (!_hasPrefix(generatedBytes, inputBytes)) {
      throw StateError('Generated artifact does not preserve the base bytes.');
    }

    if (options.checkOnly) {
      _validateExistingArtifact(
        path: options.outputPath,
        expectedBytes: generatedBytes,
        expectedStructure: generatedStructure,
      );
    } else {
      final output = File(options.outputPath);
      output.parent.createSync(recursive: true);
      output.writeAsBytesSync(generatedBytes, flush: true);
    }

    final report = _buildReport(
      inputPath: options.inputPath,
      outputPath: options.outputPath,
      labelsPath: options.labelsPath,
      reportPath: options.reportPath,
      labels: labels,
      baseBytes: inputBytes,
      generatedBytes: generatedBytes,
      baseStructure: baseStructure,
      generatedStructure: generatedStructure,
      metadataBytes: metadataBytes,
      checkOnly: options.checkOnly,
    );
    if (!options.checkOnly && options.reportPath != null) {
      final reportFile = File(options.reportPath!);
      reportFile.parent.createSync(recursive: true);
      reportFile.writeAsStringSync(report, flush: true);
    }

    stdout.writeln(
      '${options.checkOnly ? 'Validated' : 'Generated'} ${options.outputPath}',
    );
    stdout.writeln('  labels: ${labels.length}');
    stdout.writeln('  metadata bytes: ${metadataBytes.length}');
    stdout.writeln('  base bytes: ${inputBytes.length}');
    stdout.writeln('  generated bytes: ${generatedBytes.length}');
    stdout.writeln('  base SHA-256: ${_sha256Hex(inputBytes)}');
    stdout.writeln('  generated SHA-256: ${_sha256Hex(generatedBytes)}');
    if (!options.checkOnly && options.reportPath != null) {
      stdout.writeln('  report: ${options.reportPath}');
    }
  } on FormatException catch (error) {
    stderr.writeln('ERROR: ${error.message}');
    exitCode = 64;
  } on FileSystemException catch (error) {
    stderr.writeln('ERROR: ${error.message}');
    exitCode = 66;
  } on StateError catch (error) {
    stderr.writeln('ERROR: $error');
    exitCode = 1;
  }
}

void _validateExistingArtifact({
  required String path,
  required Uint8List expectedBytes,
  required TfliteModelStructure expectedStructure,
}) {
  final output = File(path);
  if (!output.existsSync()) {
    throw StateError('Cannot validate missing generated artifact: $path');
  }
  final actualBytes = output.readAsBytesSync();
  if (!_sameBytes(actualBytes, expectedBytes)) {
    throw StateError(
      'Generated artifact $path does not match deterministic packaging output.',
    );
  }
  final actualStructure = _requireStructure(actualBytes, path);
  _assertSameStructure(expectedStructure, actualStructure);
  if (!_zipContainsMetadata(actualBytes)) {
    throw StateError('Generated artifact $path has no readable metadata ZIP.');
  }
}

bool _sameBytes(Uint8List a, Uint8List b) {
  if (a.length != b.length) return false;
  for (var index = 0; index < a.length; index++) {
    if (a[index] != b[index]) return false;
  }
  return true;
}

bool _zipContainsMetadata(Uint8List bytes) {
  final signature = Uint8List.fromList([0x50, 0x4b, 0x03, 0x04]);
  for (var index = bytes.length - signature.length; index >= 0; index--) {
    var matches = true;
    for (var byteIndex = 0; byteIndex < signature.length; byteIndex++) {
      if (bytes[index + byteIndex] != signature[byteIndex]) {
        matches = false;
        break;
      }
    }
    if (matches) return true;
  }
  return false;
}

List<String> _readLabels(String path) {
  final lines = File(path).readAsLinesSync();
  final labels = <String>[];
  for (var index = 0; index < lines.length; index++) {
    var label = lines[index].trim();
    if (index == 0) label = label.replaceFirst('\ufeff', '');
    if (label.isEmpty) {
      throw FormatException(
        'Label file contains an empty line at ${index + 1}.',
      );
    }
    labels.add(label);
  }
  if (labels.length != _expectedLabelCount) {
    throw FormatException(
      'Expected $_expectedLabelCount labels in $path, found ${labels.length}.',
    );
  }
  final seen = <String>{};
  for (final label in labels) {
    if (!seen.add(label)) {
      throw FormatException('Label file contains a duplicate label: "$label".');
    }
  }
  return List<String>.unmodifiable(labels);
}

Map<String, dynamic> _buildMetadata(List<String> labels) => {
  'task': 'detect',
  'names': <String, String>{
    for (var index = 0; index < labels.length; index++) '$index': labels[index],
  },
};

TfliteModelStructure _requireStructure(Uint8List bytes, String path) {
  final structure = scanTfliteModelStructure(bytes);
  if (structure == null) {
    throw StateError('$path is not a readable TFLite FlatBuffer.');
  }
  return structure;
}

void _assertSameStructure(
  TfliteModelStructure base,
  TfliteModelStructure generated,
) {
  if (!_sameIntList(base.inputs, generated.inputs) ||
      !_sameIntList(base.outputs, generated.outputs) ||
      base.tensors.length != generated.tensors.length ||
      base.tensorTypeCounts.length != generated.tensorTypeCounts.length) {
    throw StateError('TFLite subgraph structure changed during packaging.');
  }

  for (var index = 0; index < base.tensors.length; index++) {
    final expected = base.tensors[index];
    final actual = generated.tensors[index];
    if (expected.index != actual.index ||
        expected.typeCode != actual.typeCode ||
        expected.bufferIndex != actual.bufferIndex ||
        !_sameIntList(expected.shape, actual.shape)) {
      throw StateError('TFLite tensor metadata changed at index $index.');
    }
  }

  for (final entry in base.tensorTypeCounts.entries) {
    if (generated.tensorTypeCounts[entry.key] != entry.value) {
      throw StateError(
        'TFLite tensor-type count changed for code ${entry.key}.',
      );
    }
  }
}

bool _sameIntList(List<int> a, List<int> b) {
  if (a.length != b.length) return false;
  for (var index = 0; index < a.length; index++) {
    if (a[index] != b[index]) return false;
  }
  return true;
}

bool _hasPrefix(Uint8List value, Uint8List prefix) {
  if (value.length < prefix.length) return false;
  for (var index = 0; index < prefix.length; index++) {
    if (value[index] != prefix[index]) return false;
  }
  return true;
}

Uint8List _buildStoredZip(String name, Uint8List content) {
  final nameBytes = Uint8List.fromList(utf8.encode(name));
  final crc = _crc32(content);
  final localHeader = BytesBuilder(copy: false)
    ..add(_u32(0x04034b50))
    ..add(_u16(20)) // version needed
    ..add(_u16(0)) // flags: no data descriptor, no encryption
    ..add(_u16(0)) // stored, no compression
    ..add(_u16(0)) // modification time
    ..add(_u16(0)) // modification date
    ..add(_u32(crc))
    ..add(_u32(content.length))
    ..add(_u32(content.length))
    ..add(_u16(nameBytes.length))
    ..add(_u16(0)) // extra field length
    ..add(nameBytes)
    ..add(content);
  final localBytes = localHeader.takeBytes();

  final centralDirectory = BytesBuilder(copy: false)
    ..add(_u32(0x02014b50))
    ..add(_u16(20)) // version made by
    ..add(_u16(20)) // version needed
    ..add(_u16(0))
    ..add(_u16(0))
    ..add(_u16(0))
    ..add(_u16(0))
    ..add(_u32(crc))
    ..add(_u32(content.length))
    ..add(_u32(content.length))
    ..add(_u16(nameBytes.length))
    ..add(_u16(0)) // extra field length
    ..add(_u16(0)) // comment length
    ..add(_u16(0)) // disk number
    ..add(_u16(0)) // internal attributes
    ..add(_u32(0)) // external attributes
    ..add(_u32(0)) // local header offset relative to ZIP start
    ..add(nameBytes);
  final centralBytes = centralDirectory.takeBytes();

  return (BytesBuilder(copy: false)
        ..add(localBytes)
        ..add(centralBytes)
        ..add(_u32(0x06054b50))
        ..add(_u16(0)) // disk number
        ..add(_u16(0)) // central-directory disk
        ..add(_u16(1)) // entries on this disk
        ..add(_u16(1)) // total entries
        ..add(_u32(centralBytes.length))
        ..add(_u32(localBytes.length))
        ..add(_u16(0))) // comment length
      .takeBytes();
}

Uint8List _u16(int value) {
  final data = ByteData(2)..setUint16(0, value, Endian.little);
  return data.buffer.asUint8List();
}

Uint8List _u32(int value) {
  final data = ByteData(4)..setUint32(0, value, Endian.little);
  return data.buffer.asUint8List();
}

int _crc32(Uint8List bytes) {
  var crc = 0xffffffff;
  for (final byte in bytes) {
    crc ^= byte;
    for (var bit = 0; bit < 8; bit++) {
      crc = (crc & 1) == 0 ? crc >>> 1 : (crc >>> 1) ^ 0xedb88320;
    }
  }
  return (~crc) & 0xffffffff;
}

String _buildReport({
  required String inputPath,
  required String outputPath,
  required String labelsPath,
  required String? reportPath,
  required List<String> labels,
  required Uint8List baseBytes,
  required Uint8List generatedBytes,
  required TfliteModelStructure baseStructure,
  required TfliteModelStructure generatedStructure,
  required Uint8List metadataBytes,
  required bool checkOnly,
}) {
  final baseHash = _sha256Hex(baseBytes);
  final generatedHash = _sha256Hex(generatedBytes);
  final metadataJson = utf8.decode(metadataBytes);
  final inputLink = _markdownLink(inputPath, reportPath);
  final outputLink = _markdownLink(outputPath, reportPath);
  final labelsLink = _markdownLink(labelsPath, reportPath);
  final mode = checkOnly ? 'validated' : 'generated';

  return '''# Model assets

This record describes the metadata-enriched TFLite artifact used by the
Ultralytics detection engine. The metadata suffix is packaging-only: the generated file
starts with the exact bytes of the base FlatBuffer and adds one deterministic
stored ZIP entry named `metadata.json`.

## Artifact record

| Field | Value |
|---|---|
| Base graph | $inputLink |
| Runtime artifact | $outputLink |
| Labels source | $labelsLink |
| Packaging status | $mode |
| Label count | ${labels.length} |
| Base size | ${baseBytes.length} bytes |
| Generated size | ${generatedBytes.length} bytes |
| Metadata payload | `${metadataBytes.length}` bytes |
| Base graph SHA-256 | `$baseHash` |
| Runtime artifact SHA-256 | `$generatedHash` |
| Primary-subgraph tensor count | ${baseStructure.tensors.length} |
| Generated tensor count | ${generatedStructure.tensors.length} |
| Primary-subgraph type counts | `${baseStructure.tensorTypeCounts}` |

## Native metadata payload

The native Ultralytics loader accepts the following deterministic JSON shape and
converts the numeric `names` keys into class-index order:

```json
$metadataJson
```

`labels.txt` remains authoritative. The packaging utility rejects empty or
duplicate labels and requires exactly 80 entries, so class index 41 resolves to
`cup` in the native metadata and in EyeCue's normalized detection adapter.

## Validation guarantees

- The generated artifact preserves the complete base FlatBuffer byte-for-byte.
- Primary-subgraph input/output indices, tensor shapes, tensor types, buffer
  indices, and internal tensor-type counts match the base artifact.
- The ZIP entry uses fixed timestamps, fixed attributes, and no compression so
  identical inputs produce identical output bytes.
- No weights, operators, tensor buffers, or learned parameters are rewritten.

Regenerate or validate with:

```text
dart run tool/package_ultralytics_metadata.dart --input=<base>.tflite
dart run tool/package_ultralytics_metadata.dart --check --input=<base>.tflite
```
''';
}

String _markdownLink(String path, String? reportPath) {
  if (reportPath == null) return '`$path`';
  final from = File(reportPath).parent.path;
  final relative = _relativePath(from, path);
  return '[`$path`]($relative)';
}

String _relativePath(String from, String to) {
  final fromParts = _pathParts(from);
  final toParts = _pathParts(to);
  while (fromParts.isNotEmpty &&
      toParts.isNotEmpty &&
      fromParts.first == toParts.first) {
    fromParts.removeAt(0);
    toParts.removeAt(0);
  }
  return '${List<String>.filled(fromParts.length, '..').join('/')}'
      '${fromParts.isEmpty || toParts.isEmpty ? '' : '/'}'
      '${toParts.join('/')}';
}

List<String> _pathParts(String path) => path
    .replaceAll('\\', '/')
    .split('/')
    .where((part) => part.isNotEmpty && part != '.')
    .toList();

String _sha256Hex(Uint8List input) {
  final digest = _Sha256()..add(input);
  return digest
      .close()
      .map((byte) => byte.toRadixString(16).padLeft(2, '0'))
      .join();
}

class _Sha256 {
  static const _roundConstants = <int>[
    0x428a2f98,
    0x71374491,
    0xb5c0fbcf,
    0xe9b5dba5,
    0x3956c25b,
    0x59f111f1,
