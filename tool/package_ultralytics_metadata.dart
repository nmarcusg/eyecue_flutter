    0xa81a664b,
    0xc24b8b70,
    0xc76c51a3,
    0xd192e819,
    0xd6990624,
    0xf40e3585,
    0x106aa070,
    0x19a4c116,
    0x1e376c08,
    0x2748774c,
    0x34b0bcb5,
    0x391c0cb3,
    0x4ed8aa4a,
    0x5b9cca4f,
    0x682e6ff3,
    0x748f82ee,
    0x78a5636f,
    0x84c87814,
    0x8cc70208,
    0x90befffa,
    0xa4506ceb,
    0xbef9a3f7,
    0xc67178f2,
  ];

  final _state = <int>[
    0x6a09e667,
    0xbb67ae85,
    0x3c6ef372,
    0xa54ff53a,
    0x510e527f,
    0x9b05688c,
    0x1f83d9ab,
    0x5be0cd19,
  ];
  final _buffer = BytesBuilder(copy: false);
  int _length = 0;

  void add(Uint8List bytes) {
    _length += bytes.length;
    _buffer.add(bytes);
    var pending = _buffer.takeBytes();
    var offset = 0;
    while (pending.length - offset >= 64) {
      _compress(pending, offset);
      offset += 64;
    }
    if (offset < pending.length) {
      _buffer.add(pending.sublist(offset));
    }
  }

  Uint8List close() {
    final pending = _buffer.takeBytes();
    final bitLength = _length * 8;
    final paddedLength = ((pending.length + 1 + 8 + 63) ~/ 64) * 64;
    final padded = Uint8List(paddedLength)
      ..setRange(0, pending.length, pending)
      ..[pending.length] = 0x80;
    final lengthData = ByteData.sublistView(padded);
    lengthData.setUint64(padded.length - 8, bitLength, Endian.big);
    for (var offset = 0; offset < padded.length; offset += 64) {
      _compress(padded, offset);
    }

    final output = ByteData(32);
    for (var index = 0; index < _state.length; index++) {
      output.setUint32(index * 4, _state[index], Endian.big);
    }
    return output.buffer.asUint8List();
  }

  void _compress(Uint8List bytes, int offset) {
    final schedule = List<int>.filled(64, 0);
    final data = ByteData.sublistView(bytes, offset, offset + 64);
    for (var index = 0; index < 16; index++) {
      schedule[index] = data.getUint32(index * 4, Endian.big);
    }
    for (var index = 16; index < 64; index++) {
      final s0 =
          _rightRotate(schedule[index - 15], 7) ^
          _rightRotate(schedule[index - 15], 18) ^
          (schedule[index - 15] >>> 3);
      final s1 =
          _rightRotate(schedule[index - 2], 17) ^
          _rightRotate(schedule[index - 2], 19) ^
          (schedule[index - 2] >>> 10);
      schedule[index] =
          (schedule[index - 16] + s0 + schedule[index - 7] + s1) & 0xffffffff;
    }

    var a = _state[0];
    var b = _state[1];
    var c = _state[2];
    var d = _state[3];
    var e = _state[4];
    var f = _state[5];
    var g = _state[6];
    var h = _state[7];

    for (var index = 0; index < 64; index++) {
      final s1 = _rightRotate(e, 6) ^ _rightRotate(e, 11) ^ _rightRotate(e, 25);
      final choose = (e & f) ^ ((~e) & g);
      final temp1 =
          (h + s1 + choose + _roundConstants[index] + schedule[index]) &
          0xffffffff;
      final s0 = _rightRotate(a, 2) ^ _rightRotate(a, 13) ^ _rightRotate(a, 22);
      final majority = (a & b) ^ (a & c) ^ (b & c);
      final temp2 = (s0 + majority) & 0xffffffff;
      h = g;
      g = f;
      f = e;
      e = (d + temp1) & 0xffffffff;
      d = c;
      c = b;
      b = a;
      a = (temp1 + temp2) & 0xffffffff;
    }

    _state[0] = (_state[0] + a) & 0xffffffff;
    _state[1] = (_state[1] + b) & 0xffffffff;
    _state[2] = (_state[2] + c) & 0xffffffff;
    _state[3] = (_state[3] + d) & 0xffffffff;
    _state[4] = (_state[4] + e) & 0xffffffff;
    _state[5] = (_state[5] + f) & 0xffffffff;
    _state[6] = (_state[6] + g) & 0xffffffff;
    _state[7] = (_state[7] + h) & 0xffffffff;
  }

  static int _rightRotate(int value, int amount) =>
      ((value >>> amount) | (value << (32 - amount))) & 0xffffffff;
}

class _Options {
  final String inputPath;
  final String outputPath;
  final String labelsPath;
  final String? reportPath;
  final bool checkOnly;

  const _Options({
    required this.inputPath,
    required this.outputPath,
    required this.labelsPath,
    required this.reportPath,
    required this.checkOnly,
  });

  static _Options parse(List<String> args) {
    var inputPath = _defaultInput;
    var outputPath = _defaultOutput;
    var labelsPath = _defaultLabels;
    String? reportPath;
    var checkOnly = false;

    for (var index = 0; index < args.length; index++) {
      final argument = args[index];
      if (argument == '--check') {
        checkOnly = true;
        continue;
      }
      if (argument == '--no-report') {
        reportPath = null;
        continue;
      }
      final separator = argument.indexOf('=');
      final name = separator == -1
          ? argument
          : argument.substring(0, separator);
      final inlineValue = separator == -1
          ? null
          : argument.substring(separator + 1);
      if (name == '--input' ||
          name == '--output' ||
          name == '--labels' ||
          name == '--report') {
        final value =
            inlineValue ?? (index + 1 < args.length ? args[++index] : null);
        if (value == null || value.isEmpty) {
          throw FormatException('$name requires a value.');
        }
        switch (name) {
          case '--input':
            inputPath = value;
          case '--output':
            outputPath = value;
          case '--labels':
            labelsPath = value;
          case '--report':
            reportPath = value;
        }
        continue;
      }
      throw FormatException('Unknown argument: $argument');
    }

    if (inputPath.isEmpty) {
      throw FormatException(
        'Pass --input=<base .tflite graph> (the base artifact is not vendored).',
      );
    }
    if (File(inputPath).absolute.path == File(outputPath).absolute.path) {
      throw FormatException(
        'Input and output must be different paths so the base artifact stays available.',
      );
    }
    return _Options(
      inputPath: inputPath,
      outputPath: outputPath,
      labelsPath: labelsPath,
      reportPath: reportPath,
      checkOnly: checkOnly,
    );
  }
}
